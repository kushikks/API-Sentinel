import { useEffect, useState } from 'react'
import { useMutation } from '@tanstack/react-query'
import { ApiError, useSession } from '../auth/session'
import './migration-suggestions.css'

type Suggestion = {
  findingId: string
  severity: 'BREAKING' | 'POTENTIALLY_BREAKING'
  category: string
  httpMethod: string | null
  path: string | null
  jsonPath: string | null
  explanation: string
  affectedClientCode: string
  recommendedChanges: string[]
  verificationSteps: string[]
}

type SuggestionResponse = {
  analysisId: string
  source: 'GEMINI'
  model: string
  verified: false
  eligibleFindingCount: number
  suggestions: Suggestion[]
}

export function MigrationSuggestions({ analysisId, hasEligibleFindings }: {
  analysisId: string; hasEligibleFindings: boolean
}) {
  const { client } = useSession()
  const [retryUntil, setRetryUntil] = useState(0)
  const [secondsLeft, setSecondsLeft] = useState(0)
  const generation = useMutation({
    mutationFn: () => client.json<SuggestionResponse>('/analyses/' + analysisId + '/migration-suggestions', { method: 'POST' }),
    onError: error => {
      if (error instanceof ApiError && error.status === 429) {
        const wait = error.retryAfterSeconds ?? 30
        setSecondsLeft(wait)
        setRetryUntil(Date.now() + wait * 1000)
      }
    },
  })

  useEffect(() => {
    if (!retryUntil) return
    const timer = window.setInterval(() => {
      const remaining = Math.max(0, Math.ceil((retryUntil - Date.now()) / 1000))
      setSecondsLeft(remaining)
      if (remaining === 0) window.clearInterval(timer)
    }, 250)
    return () => window.clearInterval(timer)
  }, [retryUntil])

  const data = generation.data
  const disabled = generation.isPending || secondsLeft > 0
  const label = generation.isPending ? 'Generating…' : secondsLeft > 0 ? 'Try again in ' + secondsLeft + 's'
    : generation.isError ? 'Try again' : data ? 'Generate again' : 'Generate suggestions'

  return <section className="surface migration-panel" aria-labelledby="migration-suggestions-heading">
    <header className="migration-heading">
      <span className="migration-icon" aria-hidden="true">✧</span>
      <div className="migration-intro">
        <div className="migration-title">
          <h2 id="migration-suggestions-heading">AI Suggestions</h2>
          <span className="migration-label">Unverified</span>
        </div>
        <p>{hasEligibleFindings
          ? 'Send up to five saved finding summaries to Gemini. Review its advice against your client code before applying changes.'
          : 'This comparison has no breaking or potentially breaking findings to review.'}</p>
      </div>
      {hasEligibleFindings && <button type="button" className="button secondary migration-generate"
        onClick={() => generation.mutate()} disabled={disabled}>{label}</button>}
    </header>
    {(generation.isPending || generation.isError || data) && <div className="migration-content">
      {generation.isPending && <p className="migration-progress" role="status">
        <span className="spinner" aria-hidden="true" /> Gemini is reviewing the selected contract findings…
      </p>}
      {generation.isError && <div className="migration-fallback feedback" role="alert">
        <p>{generation.error.message}</p>
        <a href="#findings-title">Review the compatibility findings</a>
      </div>}
      {data && <>
        <p className="migration-disclosure" role="status">
          AI-generated by Gemini. Review these recommendations against your SDKs and client code.
          {data.suggestions.length < data.eligibleFindingCount && ' Covers ' + data.suggestions.length
            + ' of ' + data.eligibleFindingCount + ' eligible findings.'}
        </p>
        <div className="migration-cards">
          {data.suggestions.map((suggestion, index) => <details className="migration-card" key={suggestion.findingId} open={index === 0}>
            <summary>
              <span className={'badge ' + suggestion.severity.toLowerCase()}>
                {suggestion.severity === 'BREAKING' ? 'Breaking' : 'Potentially breaking'}
              </span>
              <strong>{suggestion.category.toLowerCase().replaceAll('_', ' ')}</strong>
              {suggestion.path && <span className="mono migration-endpoint">
                {suggestion.httpMethod && suggestion.httpMethod + ' '}{suggestion.path}
              </span>}
              <span className="migration-chevron" aria-hidden="true" />
            </summary>
            <div className="migration-detail">
              {suggestion.jsonPath && <div className="migration-path mono">{suggestion.jsonPath}</div>}
              <div className="migration-context">
                <div><h3>What changed</h3><p>{suggestion.explanation}</p></div>
                <div><h3>Client code to check</h3><p>{suggestion.affectedClientCode}</p></div>
              </div>
              <div className="migration-context">
                <div><h3>Recommended changes</h3><ol>
                  {suggestion.recommendedChanges.map((step, order) => <li key={order}>{step}</li>)}
                </ol></div>
                <div><h3>Verification steps</h3><ol>
                  {suggestion.verificationSteps.map((step, order) => <li key={order}>{step}</li>)}
                </ol></div>
              </div>
            </div>
          </details>)}
        </div>
      </>}
    </div>}
  </section>
}
