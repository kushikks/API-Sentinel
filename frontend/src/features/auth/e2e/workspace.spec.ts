import { expect, test, type Page } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const fixture = (name: string) => fileURLToPath(new URL('../../../../../tests/developer-a/fixtures/' + name, import.meta.url))

test('owner creates an API, uploads two contracts, reads findings and downloads the report', async ({ page }, info) => {
  const name = 'Student API ' + randomUUID().slice(0, 8)
  await createAccount(page, 'API_OWNER')
  await page.getByRole('button', { name: 'Register API' }).click()
  await page.getByLabel('API name').fill(name)
  await page.getByLabel('Base URL').fill('https://students.example.test')
  await page.getByLabel('Description').fill('Student record contract')
  await page.getByRole('button', { name: 'Create API' }).click()
  await expect(page.getByRole('heading', { name })).toBeVisible()

  await upload(page, '1.0.0', 'student-v1.yaml')
  await upload(page, '2.0.0', 'student-v2.json')
  await expect(page.getByRole('cell', { name: /2\.0\.0/ }).first()).toBeVisible()

  await page.getByLabel('Baseline version').selectOption({ label: '1.0.0' })
  await page.getByRole('button', { name: 'Run comparison' }).click()
  await expect(page.getByRole('heading', { name: 'Compatibility findings' })).toBeVisible({ timeout: 50_000 })
  await expect(page.getByRole('heading', { name: 'The response property studentId was removed.' })).toBeVisible()
  const breaking = page.getByRole('button', { name: 'Breaking findings', exact: true })
  await breaking.click()
  await expect(breaking).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('combobox', { name: 'Severity' })).toHaveValue('BREAKING')
  await expect(page.getByRole('heading', { name: 'The response property id was added.' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'The response property name was removed.' })).toBeVisible()

  const suggestions = page.getByRole('region', { name: 'AI Suggestions' })
  await expect(suggestions.getByText('Unverified', { exact: true })).toBeVisible()
  let aiRequests = 0
  await page.route('**/analyses/*/migration-suggestions', async route => {
    aiRequests += 1
    expect(route.request().method()).toBe('POST')
    expect(route.request().postData()).toBeNull()
    expect(route.request().headers()['x-goog-api-key']).toBeUndefined()
    if (aiRequests === 1) {
      await route.fulfill({ status: 429, json: { code: 'GEMINI_RATE_LIMITED',
        detail: 'Gemini is rate limited. Try again after the cooldown.', retryAfterSeconds: 2 } })
    } else if (aiRequests === 2) {
      await route.fulfill({ status: 503, json: { code: 'GEMINI_UNAVAILABLE',
        detail: 'Gemini is temporarily unavailable. Try again later.' } })
    } else {
      await route.fulfill({ json: {
        analysisId: new URL(page.url()).pathname.split('/').at(-1),
        source: 'GEMINI', model: 'fixture', verified: false, eligibleFindingCount: 2,
        suggestions: [{
          findingId: 'fixture-student-id', severity: 'BREAKING', category: 'RESPONSE_PROPERTY_REMOVED',
          httpMethod: 'GET', path: '/api/students/{id}', jsonPath: '$.studentId',
          explanation: 'The studentId response field was removed.',
          affectedClientCode: 'Review client DTOs and mappers that read studentId.',
          recommendedChanges: ['Update the response mapper to match the revised contract.'],
          verificationSteps: ['Deserialize a sample response without studentId.'],
        }],
      } })
    }
  })
  await suggestions.getByRole('button', { name: 'Generate suggestions' }).click()
  await expect(suggestions.getByRole('alert')).toContainText('Gemini is rate limited')
  await expect(suggestions.getByRole('button', { name: /Try again in/ })).toBeDisabled()
  await suggestions.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(suggestions.getByRole('alert')).toContainText('Gemini is temporarily unavailable')
  await expect(suggestions.getByRole('link', { name: 'Review the compatibility findings' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'The response property studentId was removed.' })).toBeVisible()
  await suggestions.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(suggestions.getByRole('status')).toContainText('AI-generated by Gemini')
  await expect(suggestions.getByText('The studentId response field was removed.')).toBeVisible()
  await expect(suggestions.getByText('Review client DTOs and mappers that read studentId.')).toBeVisible()
  await expect(suggestions.getByText('Update the response mapper to match the revised contract.')).toBeVisible()
  await expect(suggestions.getByText('Deserialize a sample response without studentId.')).toBeVisible()
  await expect(suggestions.getByRole('status')).toContainText('Covers 1 of 2 eligible findings.')
  expect(aiRequests).toBe(3)
  await page.screenshot({ path: info.outputPath('migration-suggestions.png') })

  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download report' }).click()])
  expect(download.suggestedFilename()).toMatch(/^compatibility-.*\.json$/)
  const report = JSON.parse(await readFile(await download.path(), 'utf8'))
  expect(report.analysis.breakingCount).toBe(2)
  expect(report.findings).toHaveLength(4)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Compatibility findings' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('analysis-dark.png') })
  const comparisonPath = new URL(page.url()).pathname
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('link', { name: 'API registry' }).click()
  const registered = page.getByRole('region', { name: 'Registered APIs' })
  await expect(registered.getByRole('link', { name: new RegExp(name) })).toBeVisible()
  const activity = page.getByRole('region', { name: 'Recent analyses' })
  const latestRun = activity.locator('a[href="' + comparisonPath + '"]')
  await expect(latestRun).toContainText('Completed')
  await page.screenshot({ path: info.outputPath('registry-dark.png') })
  await page.getByRole('button', { name: 'Table view' }).click()
  await expect(registered.getByRole('table')).toBeVisible()
  await expect(registered.getByRole('cell', { name: new RegExp(name) })).toBeVisible()
  await page.getByRole('button', { name: 'Card view' }).click()
  await expect(registered.getByRole('table')).toHaveCount(0)
  await page.getByRole('button', { name: 'Light' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: info.outputPath('registry-light.png'), animations: 'disabled' })
  await latestRun.click()
  await expect(page.getByRole('heading', { name: 'Compatibility findings' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('analysis-light.png'), animations: 'disabled' })
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Light' })).toHaveAttribute('aria-pressed', 'true')
})

test('consumer dashboard is readable on mobile and hides write actions', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await createAccount(page, 'CONSUMER')
  await expect(page.getByRole('heading', { name: 'API registry' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Register API' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'No registered APIs' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: info.outputPath('registry-mobile.png'), fullPage: true })
  await page.getByRole('link', { name: 'Analysis history' }).click()
  await expect(page.getByRole('heading', { name: 'No matching analyses' })).toBeVisible()
})

test('sign-in supports persistent themes, password visibility and reduced motion', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/sign-in')
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  const html = page.locator('html')
  await expect(html).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: info.outputPath('sign-in-dark.png') })

  const card = page.locator('.art-before')
  const originalTransform = await card.evaluate(element => getComputedStyle(element).transform)
  await page.locator('.auth-art').hover()
  await expect.poll(() => card.evaluate(element => getComputedStyle(element).transform)).not.toBe(originalTransform)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.firefly').first()).toHaveCSS('animation-name', 'none')
  await expect(card).toHaveCSS('transform', originalTransform)

  const password = page.getByLabel('Password', { exact: true })
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Show password' }).click()
  await expect(password).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Hide password' }).click()
  await expect(password).toHaveAttribute('type', 'password')

  await page.getByRole('button', { name: 'Light' }).click()
  await expect(html).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Light' })).toHaveAttribute('aria-pressed', 'true')
  await expect(html).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: info.outputPath('sign-in-light.png') })

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Dark' }).click()
  await expect(html).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: info.outputPath('sign-in-mobile.png') })
})

async function createAccount(page: Page, role: string) {
  const email = 'browser-' + randomUUID() + '@example.test'
  const password = randomUUID()
  await page.goto('/catalog')
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  await page.getByRole('link', { name: 'Create an account' }).click()
  await page.getByLabel('Display name').fill('Test Analyst')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByLabel('Role').selectOption(role)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByText('Account created. Sign in to continue.')).toBeVisible()
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'API registry' })).toBeVisible()
}

async function upload(page: Page, label: string, filename: string) {
  await page.getByRole('button', { name: 'Upload version' }).click()
  await page.getByLabel('Version label').fill(label)
  await page.getByLabel('Specification file').setInputFiles(fixture(filename))
  await page.getByRole('button', { name: 'Save version' }).click()
  await expect(page.getByText('Version ' + label + ' uploaded. Analysis submitted.')).toBeVisible()
}
